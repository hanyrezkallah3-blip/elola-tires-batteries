export default class VehicleCache {

  static storage = new Map()

  // ====================================================
  // GET
  // ====================================================

  static get(key) {

    return this.storage.get(key)

  }

  // ====================================================
  // SET
  // ====================================================

  static set(

    key,

    value

  ) {

    this.storage.set(

      key,

      value

    )

    return value

  }

  // ====================================================
  // HAS
  // ====================================================

  static has(key) {

    return this.storage.has(key)

  }

  // ====================================================
  // REMOVE
  // ====================================================

  static remove(key) {

    this.storage.delete(key)

  }

  // ====================================================
  // CLEAR
  // ====================================================

  static clear() {

    this.storage.clear()

  }

  // ====================================================
  // SIZE
  // ====================================================

  static size() {

    return this.storage.size

  }

  // ====================================================
  // KEYS
  // ====================================================

  static keys() {

    return [

      ...this.storage.keys()

    ]

  }

  // ====================================================
  // VALUES
  // ====================================================

  static values() {

    return [

      ...this.storage.values()

    ]

  }

}