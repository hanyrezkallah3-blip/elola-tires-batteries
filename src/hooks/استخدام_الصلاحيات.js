import { usePermissionsStore } from '../store/الصلاحيات_العربية'

export default function استخدام_الصلاحيات() {

  const يملك_صلاحية =
    usePermissionsStore(
      (s) => s.يملك_صلاحية
    )

  return {
    لوحة_تحكم: يملك_صلاحية('لوحة_تحكم'),
    منتجات: يملك_صلاحية('منتجات'),
    مخازن: يملك_صلاحية('مخازن'),
    مخزون: يملك_صلاحية('مخزون'),
    طلبات: يملك_صلاحية('طلبات'),
    تقارير: يملك_صلاحية('تقارير'),
    مستخدمين: يملك_صلاحية('مستخدمين')
  }

}