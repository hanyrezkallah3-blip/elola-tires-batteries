import { create } from 'zustand'

export const useAIERPStore = create((set, get) => ({

  // ================= STATE =================

  تحليل: {
    اتجاه_المبيعات: 'ثابت',
    خطر_المخزون: 'منخفض',
    افضل_منتج: null,
    اضعف_منتج: null,
    توقع_الشهر_القادم: 0,
    توصية_نظام: ''
  },

  // ================= ANALYZE SYSTEM =================

  تحليل_النظام: ({
    منتجات = [],
    طلبات = [],
    مخزون = []
  }) => {

    // ================= TOTAL SALES =================

    const المبيعات_الكلية =
      طلبات.reduce(
        (a, o) => a + Number(o.total || 0),
        0
      )

    // ================= TREND =================

    const اتجاه =
      المبيعات_الكلية > 100000
        ? 'صاعد'
        : المبيعات_الكلية > 50000
        ? 'متوسط'
        : 'ضعيف'

    // ================= LOW STOCK =================

    const المنتجات_الخطيرة =
      مخزون.filter(
        (i) => Number(i.quantity || 0) <= 5
      )

    const خطر =
      المنتجات_الخطيرة.length > 5
        ? 'مرتفع'
        : 'منخفض'

    // ================= BEST PRODUCT =================

    const افضل_منتج =
      [...منتجات].sort(
        (a, b) =>
          Number(b.sold || 0) -
          Number(a.sold || 0)
      )[0]

    // ================= WORST PRODUCT =================

    const اضعف_منتج =
      [...منتجات].sort(
        (a, b) =>
          Number(a.sold || 0) -
          Number(b.sold || 0)
      )[0]

    // ================= PREDICTION =================

    const توقع =
      Math.round(
        المبيعات_الكلية * 1.15
      )

    // ================= AI RECOMMENDATION =================

    let توصية = ''

    if (خطر === 'مرتفع') {
      توصية = '⚠ يجب إعادة تعبئة المخزون فوراً'
    } else if (اتجاه === 'ضعيف') {
      توصية = '📉 تحسين التسويق مطلوب'
    } else {
      توصية = '📈 النظام يعمل بشكل جيد'
    }

    // ================= SAVE =================

    set({
      تحليل: {
        اتجاه_المبيعات: اتجاه,
        خطر_المخزون: خطر,
        افضل_منتج,
        اضعف_منتج,
        توقع_الشهر_القادم: توقع,
        توصية_نظام: توصية
      }
    })

  }

}))