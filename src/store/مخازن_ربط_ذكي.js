import { useWebsiteStore } from '../store/websiteStore'
import { استخدام_مخازن_النظام_العربي } from './مخازن_النظام_العربي'

// ================= جسر بين النظامين =================

export const استخدام_مخازن_موحد = () => {

  const القديم = useWebsiteStore()
  const الجديد = استخدام_مخازن_النظام_العربي()

  // ================= قراءة موحدة =================

  const المخازن = {
    قديم: القديم.warehouses || [],
    جديد: الجديد.المخازن || []
  }

  const المخزون = {
    قديم: القديم.stockItems || [],
    جديد: الجديد.عناصر_المخزون || []
  }

  const الحركات = {
    قديم: القديم.stockHistory || [],
    جديد: الجديد.حركات_المخزون || []
  }

  // ================= عمليات موحدة =================

  const إضافة_مخزن = (data) => {

    // يكتب في النظام الجديد فقط
    return الجديد.إضافة_مخزن(data)
  }

  const إضافة_عنصر_مخزون = (data) => {

    return الجديد.إضافة_عنصر_مخزون(data)
  }

  const نقل_مخزون = (data) => {

    return الجديد.زيادة_المخزون(data)
  }

  const تقليل_مخزون = (data) => {

    return الجديد.تقليل_المخزون(data)
  }

  // ================= Analytics موحد =================

  const ملخص = الجديد.ملخص_المخزون()

  const منخفض = الجديد.الحصول_على_العناصر_المنخفضة()

  // ================= Return =================

  return {

    // قراءة
    المخازن,
    المخزون,
    الحركات,

    // عمليات
    إضافة_مخزن,
    إضافة_عنصر_مخزون,
    نقل_مخزون,
    تقليل_مخزون,

    // تحليلات
    ملخص,
    منخفض

  }
}