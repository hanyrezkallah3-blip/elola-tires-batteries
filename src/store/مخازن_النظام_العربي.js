import { create } from 'zustand'
import { persist } from 'zustand/middleware'

// ================= مولد رقم تعريف =================
const توليد_معرف = () =>
  Date.now() + Math.random()

export const استخدام_مخازن_النظام_العربي = create(
  persist(
    (تعيين, احصل) => ({

      // ================= التحميل =================
      تم_التحميل: false,

      تعيين_التحميل: (قيمة) =>
        تعيين({ تم_التحميل: قيمة }),

      // ================= المخازن =================
      المخازن: [

        {
          معرف: 'المخزن_الرئيسي',
          اسم: 'المخزن الرئيسي',
          الموقع: 'القاهرة',
          المدير: 'الإدارة',
          نشط: true,
          تاريخ_الإنشاء: new Date().toISOString()
        }

      ],

      إضافة_مخزن: (مخزن) => {

        const مخزن_جديد = {

          معرف: توليد_معرف(),

          اسم: '',
          الموقع: '',
          المدير: '',

          نشط: true,

          تاريخ_الإنشاء: new Date().toISOString(),

          ...مخزن

        }

        تعيين((حالة) => ({

          المخازن: [
            مخزن_جديد,
            ...(حالة.المخازن || [])
          ]

        }))
      },

      تعديل_مخزن: (معرف_المخزن, بيانات) => {

        تعيين((حالة) => ({

          المخازن:
            (حالة.المخازن || []).map((مخزن) =>

              مخزن.معرف === معرف_المخزن

                ? {
                    ...مخزن,
                    ...بيانات
                  }

                : مخزن

            )

        }))
      },

      حذف_مخزن: (معرف_المخزن) => {

        تعيين((حالة) => ({

          المخازن:
            (حالة.المخازن || []).filter(

              (مخزن) =>
                مخزن.معرف !== معرف_المخزن

            )

        }))
      },

      // ================= عناصر المخزون =================
      عناصر_المخزون: [],

      تعيين_المخزون: (عناصر) =>
        تعيين({
          عناصر_المخزون:
            Array.isArray(عناصر)
              ? عناصر
              : []
        }),

      إضافة_عنصر_مخزون: (عنصر) => {

        const عنصر_جديد = {

          معرف: توليد_معرف(),

          معرف_المنتج: '',
          اسم_المنتج: '',

          معرف_المخزن: 'المخزن_الرئيسي',
          اسم_المخزن: 'المخزن الرئيسي',

          الكمية: 0,
          الحد_الأدنى: 5,

          السعر: 0,

          باركود: '',
          تصنيف: '',

          تاريخ_الإنشاء: new Date().toISOString(),
          تاريخ_التحديث: new Date().toISOString(),

          ...عنصر

        }

        تعيين((حالة) => ({

          عناصر_المخزون: [
            عنصر_جديد,
            ...(حالة.عناصر_المخزون || [])
          ]

        }))
      },

      تعديل_عنصر_مخزون: (معرف_العنصر, بيانات) => {

        تعيين((حالة) => ({

          عناصر_المخزون:
            (حالة.عناصر_المخزون || []).map((عنصر) =>

              عنصر.معرف === معرف_العنصر

                ? {
                    ...عنصر,
                    ...بيانات,
                    تاريخ_التحديث:
                      new Date().toISOString()
                  }

                : عنصر

            )

        }))
      },

      حذف_عنصر_مخزون: (معرف_العنصر) => {

        تعيين((حالة) => ({

          عناصر_المخزون:
            (حالة.عناصر_المخزون || []).filter(

              (عنصر) =>
                عنصر.معرف !== معرف_العنصر

            )

        }))
      },

      // ================= حركات المخزون =================
      حركات_المخزون: [],

      إضافة_حركة_مخزون: (حركة) => {

        const حركة_جديدة = {

          معرف: توليد_معرف(),

          معرف_المنتج: '',
          اسم_المنتج: '',

          معرف_المخزن: '',
          اسم_المخزن: '',

          الكمية: 0,

          النوع: 'إضافة',

          ملاحظة: '',

          تاريخ_الإنشاء: new Date().toISOString(),

          ...حركة

        }

        تعيين((حالة) => ({

          حركات_المخزون: [
            حركة_جديدة,
            ...(حالة.حركات_المخزون || [])
          ]

        }))
      },

      // ================= عمليات المخزون =================

      زيادة_المخزون: ({
        معرف_عنصر,
        كمية,
        ملاحظة
      }) => {

        const حالة = احصل()

        const عناصر =
          [...(حالة.عناصر_المخزون || [])]

        const عنصر =
          عناصر.find(
            (i) => i.معرف === معرف_عنصر
          )

        if (!عنصر) return

        عنصر.الكمية =
          Number(عنصر.الكمية || 0) +
          Number(كمية || 0)

        عنصر.تاريخ_التحديث =
          new Date().toISOString()

        حالة.إضافة_حركة_مخزون({

          معرف_المنتج: عنصر.معرف_المنتج,
          اسم_المنتج: عنصر.اسم_المنتج,

          معرف_المخزن: عنصر.معرف_المخزن,
          اسم_المخزن: عنصر.اسم_المخزن,

          الكمية: كمية,

          النوع: 'إضافة',

          ملاحظة:
            ملاحظة ||
            'إضافة مخزون'

        })

        تعيين({ عناصر_المخزون: عناصر })
      },

      تقليل_المخزون: ({
        معرف_عنصر,
        كمية,
        ملاحظة
      }) => {

        const حالة = احصل()

        const عناصر =
          [...(حالة.عناصر_المخزون || [])]

        const عنصر =
          عناصر.find(
            (i) => i.معرف === معرف_عنصر
          )

        if (!عنصر) return

        عنصر.الكمية =
          Number(عنصر.الكمية || 0) -
          Number(كمية || 0)

        if (عنصر.الكمية < 0)
          عنصر.الكمية = 0

        عنصر.تاريخ_التحديث =
          new Date().toISOString()

        حالة.إضافة_حركة_مخزون({

          معرف_المنتج: عنصر.معرف_المنتج,
          اسم_المنتج: عنصر.اسم_المنتج,

          معرف_المخزن: عنصر.معرف_المخزن,
          اسم_المخزن: عنصر.اسم_المخزن,

          الكمية: كمية,

          النوع: 'خصم',

          ملاحظة:
            ملاحظة ||
            'خصم مخزون'

        })

        تعيين({ عناصر_المخزون: عناصر })
      },

      // ================= التحليل =================

      الحصول_على_العناصر_المنخفضة: () => {

        return (
          احصل().عناصر_المخزون || []
        ).filter(

          (عنصر) =>
            Number(عنصر.الكمية || 0) <=
            Number(عنصر.الحد_الأدنى || 0)

        )
      },

      ملخص_المخزون: () => {

        const عناصر =
          احصل().عناصر_المخزون || []

        const منخفض =
          احصل().الحصول_على_العناصر_المنخفضة()

        const إجمالي_الكمية =
          عناصر.reduce(

            (acc, عنصر) =>
              acc +
              Number(عنصر.الكمية || 0),

            0

          )

        const إجمالي_القيمة =
          عناصر.reduce(

            (acc, عنصر) =>
              acc +
              (
                Number(عنصر.الكمية || 0) *
                Number(عنصر.السعر || 0)
              ),

            0

          )

        return {

          عدد_العناصر:
            عناصر.length,

          إجمالي_الكمية,

          إجمالي_القيمة,

          عدد_المنخفض:
            منخفض.length

        }
      }

    }),

    // ================= التخزين =================
    {
      name: 'مخازن_النظام_العربي',

      partialize: (state) => ({

        المخازن: state.المخازن,

        عناصر_المخزون: state.عناصر_المخزون,

        حركات_المخزون: state.حركات_المخزون

      }),

      onRehydrateStorage:
        () => (state) => {

          if (state)
            state.تعيين_التحميل(true)

        }

    }

  )
)